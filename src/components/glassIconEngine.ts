/* ------------------------------------------------------------------ *
 * Colours: read from the theme's CSS variables, so no raw values here
 * ------------------------------------------------------------------ */
function cssColor(host: HTMLElement, variable: string, fallback: Rgb): Rgb {
  const probe = document.createElement("span");
  probe.style.color = `var(${variable})`;
  probe.style.display = "none";
  host.appendChild(probe);
  const value = getComputedStyle(probe).color;
  probe.remove();
  const parts = value.match(/[\d.]+/g);
  if (!parts || parts.length < 3) return fallback;
  return [Number(parts[0]) / 255, Number(parts[1]) / 255, Number(parts[2]) / 255];
}
const luminance = ([r, g, b]: Rgb) => 0.2126 * r + 0.7152 * g + 0.0722 * b;

/* ------------------------------------------------------------------ *
 * Bolt -> texture + signed distance field
 * ------------------------------------------------------------------ */
const TEX = 512;
const BOX = 0.75;

// Bounding box of a path made of absolute M/L points (the bolt is a polygon).
function pathBox(d: string) {
  const nums = (d.match(/-?\d*\.?\d+/g) ?? []).map(Number);
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (let i = 0; i + 1 < nums.length; i += 2) {
    x0 = Math.min(x0, nums[i]); x1 = Math.max(x1, nums[i]);
    y0 = Math.min(y0, nums[i + 1]); y1 = Math.max(y1, nums[i + 1]);
  }
  return x1 > x0 && y1 > y0 ? { x: x0, y: y0, w: x1 - x0, h: y1 - y0 } : null;
}

function loadShape(d: string): Promise<HTMLCanvasElement> {
  const box = pathBox(d);
  if (!box) return Promise.reject(new Error("GlassIcon: the shape is empty"));
  const s = TEX / Math.max(box.w, box.h);
  const markup =
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box.x} ${box.y} ${box.w} ${box.h}" ` +
    `width="${Math.round(box.w * s)}" height="${Math.round(box.h * s)}"><path fill="#fff" d="${d}"/></svg>`;
  return new Promise((resolve, reject) => {
    const img = new Image();
    img.onload = () => {
      const out = document.createElement("canvas");
      out.width = out.height = TEX;
      const ctx = out.getContext("2d", { willReadFrequently: true });
      if (!ctx) return reject(new Error("GlassIcon: no 2D canvas"));
      const sw = img.naturalWidth || TEX;
      const sh = img.naturalHeight || TEX;
      const k = (TEX * BOX) / Math.max(sw, sh);
      ctx.imageSmoothingQuality = "high";
      ctx.drawImage(img, (TEX - sw * k) / 2, (TEX - sh * k) / 2, sw * k, sh * k);
      resolve(out);
    };
    img.onerror = () => reject(new Error("GlassIcon: the shape could not be drawn"));
    img.src = "data:image/svg+xml;charset=utf-8," + encodeURIComponent(markup);
  });
}

// Signed distance field from alpha (TinySDF method): + outside, - inside, in texture units.
function buildSdf(canvas: HTMLCanvasElement) {
  const n = TEX * TEX;
  const ctx = canvas.getContext("2d", { willReadFrequently: true });
  if (!ctx) throw new Error("GlassIcon: no 2D canvas");
  const alpha = ctx.getImageData(0, 0, TEX, TEX).data;
  const INF = 1e20;
  const outer = new Float64Array(n);
  const inner = new Float64Array(n);
  for (let i = 0; i < n; i++) {
    const a = alpha[i * 4 + 3] / 255;
    if (a >= 1) { outer[i] = 0; inner[i] = INF; }
    else if (a <= 0) { outer[i] = INF; inner[i] = 0; }
    else {
      const dd = 0.5 - a;
      outer[i] = dd > 0 ? dd * dd : 0;
      inner[i] = dd < 0 ? dd * dd : 0;
    }
  }
  const f = new Float64Array(TEX);
  const z = new Float64Array(TEX + 1);
  const v = new Uint16Array(TEX);
  edt(outer, f, v, z, INF);
  edt(inner, f, v, z, INF);
  const sdf = new Float32Array(n);
  for (let i = 0; i < n; i++) sdf[i] = (Math.sqrt(outer[i]) - Math.sqrt(inner[i])) / TEX;
  return sdf;
}

function edt(grid: Float64Array, f: Float64Array, v: Uint16Array, z: Float64Array, INF: number) {
  for (let x = 0; x < TEX; x++) edt1d(grid, x, TEX, f, v, z, INF);
  for (let y = 0; y < TEX; y++) edt1d(grid, y * TEX, 1, f, v, z, INF);
}

function edt1d(grid: Float64Array, offset: number, stride: number, f: Float64Array, v: Uint16Array, z: Float64Array, INF: number) {
  v[0] = 0;
  z[0] = -INF;
  z[1] = INF;
  f[0] = grid[offset];
  for (let q = 1, k = 0, s = 0; q < TEX; q++) {
    f[q] = grid[offset + q * stride];
    const q2 = q * q;
    do {
      const r = v[k];
      s = (f[q] - f[r] + q2 - r * r) / (q - r) / 2;
    } while (s <= z[k] && --k > -1);
    k++;
    v[k] = q;
    z[k] = s;
    z[k + 1] = INF;
  }
  for (let q = 0, k = 0; q < TEX; q++) {
    while (z[k + 1] < q) k++;
    const r = v[k];
    const qr = q - r;
    grid[offset + q * stride] = f[r] + qr * qr;
  }
}

