/**
 * WebGL2 engine behind `GlassIcon`: a clear glass droplet grows into an app-icon tile, bends the
 * bolt into colour at its rim, then settles into a flat icon plate.
 *
 * Shader and spring timeline ported from zanwei/glass-icon-reveal (MIT),
 * https://github.com/zanwei/glass-icon-reveal, via the 21st.dev "liquid glass logo reveal".
 * One fullscreen-triangle pass, no dependencies.
 */

